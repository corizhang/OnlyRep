const PY: Record<string, string> = {};
for (const [letter, chars] of PY_GROUPS) {
  for (const ch of chars) {
    if (!(ch in PY)) PY[ch] = letter;
  }
}

/** 取字符串的拼音首字母串（拉丁/数字原样保留小写，未收录字符记 '?'） */
export function initialsOf(text: string): string {
  let out = '';
  for (const ch of text) {
    if (PY[ch]) out += PY[ch];
    else if (/[A-Za-z0-9]/.test(ch)) out += ch.toLowerCase();
    else if (ch === '_') out += '_';
    else out += '?';
  }
  return out;
}

/**
 * 检索匹配：query 与 text 做「子串（大小写不敏感）或拼音首字母包含」匹配。
 * 首字母用包含而非前缀——中文变量名常只记得末段词（输入 mb 命中「全年目标」）。
 * query 为空返回 true。
 */
export function matchQuery(query: string, text: string): boolean {
  const q = query.trim().toLowerCase();
  if (q === '') return true;
  if (text.toLowerCase().includes(q)) return true;
  const ini = initialsOf(text);
  if (!ini.includes('?')) return ini.includes(q);
  // 含未收录字符时退化为：首字母串包含 query（尽力匹配）
  return ini.includes(q);
}
